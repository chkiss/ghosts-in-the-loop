export function causeFor(factionId: string, index: number): Cause {
  const pool = [...(LOCAL_CAUSES[factionId] ?? []), ...BASE_CAUSES]
  return pool[index % pool.length]
}

// Pool size, so the warning roller can sample causes without replacement.
export function causePoolSize(factionId: string): number {
  return (LOCAL_CAUSES[factionId]?.length ?? 0) + BASE_CAUSES.length
}
